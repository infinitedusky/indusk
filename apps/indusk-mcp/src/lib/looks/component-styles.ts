import postcss, { type ChildNode, type Container } from "postcss";
import valueParser from "postcss-value-parser";
import type { Foundation } from "./foundation.js";
import { elementsOf } from "./markup.js";

/**
 * A component's stylesheet (storybook-components ADR decision 10). A snapshot
 * is markup whose look comes from the app's compiled utility classes, and a
 * mockup frame loads only the foundation's `tokens.css`; so the render step
 * writes, per component, `components/<name>.css`: the app's compiled rules for
 * exactly the classes that component's snapshots use, with the build's
 * variables resolved until only the foundation's tokens remain.
 *
 * Pure: the app's compiled CSS (what the browser held while the stories
 * rendered) and the snapshots' markup come in, the stylesheet goes out. What a
 * class compiles to that no token covers is left as the build wrote it, so the
 * value check names it — the generator never decides a value is fine.
 *
 * promise: mockups-render-in-the-cockpit
 */

export const STYLESHEET_HEADER =
	"/* Generated by `indusk looks stories` from the app's compiled CSS — do not edit. */\n";

/** The classes the markup's elements carry. */
export function classesOf(html: string): Set<string> {
	const classes = new Set<string>();
	for (const el of elementsOf(html)) {
		for (const c of (el.attrs.class ?? "").split(/\s+/)) if (c) classes.add(c);
	}
	return classes;
}

const MARK_IN_SELECTOR = /\[data-component=["']?([\w-]+)["']?\]/g;

/** The component names a selector is anchored on: `[data-component="decision-card"] p` -> decision-card. */
const selectorMarks = (selector: string): string[] =>
	[...selector.matchAll(MARK_IN_SELECTOR)].map((m) => m[1] as string);

const CLASS_IN_SELECTOR = /\.((?:\\[0-9a-fA-F]{1,6}\s?|\\.|[\w-])+)/g;

const unescapeCss = (s: string): string =>
	s.replace(/\\([0-9a-fA-F]{1,6})\s?|\\(.)/g, (_m, hex: string | undefined, ch: string) =>
		hex ? String.fromCodePoint(Number.parseInt(hex, 16)) : ch,
	);

/** The class names a selector writes, unescaped. */
function selectorClasses(selector: string): string[] {
	return [...selector.matchAll(CLASS_IN_SELECTOR)].map((m) => unescapeCss(m[1] as string));
}

/** Wrappers a utility rule sits in that are kept around it. A `@layer` is not one: see `keepRules`. */
const WRAPPERS = new Set(["media", "supports", "container"]);

/** Tailwind's theme namespace for a foundation group, and the foundation's name behind each theme name. */
const THEME_GROUP: Readonly<Record<string, string>> = {
	space: "spacing",
	size: "spacing",
	easing: "ease",
};

/** `--spacing-badge` -> `--size-badge`: what the build's variable is called in the foundation. */
function themeNames(foundation: Foundation): Map<string, string> {
	const names = new Map<string, string>();
	for (const t of foundation.tokens) {
		const [group, ...rest] = t.path;
		const mapped = THEME_GROUP[group ?? ""];
		if (mapped) names.set(`--${[mapped, ...rest].join("-")}`, t.name);
		names.set(t.name, t.name);
	}
	return names;
}

/** The foundation groups a property's raw value may be read as a token of. */
const PROPERTY_GROUPS: ReadonlyArray<[RegExp, readonly string[]]> = [
	[/^(border(-.+)?-width|outline-width)$/, ["border"]],
	[/^outline-offset$/, ["border", "space"]],
	[/^letter-spacing$/, ["tracking"]],
	[/^font-size$/, ["text"]],
	[/^line-height$/, ["leading"]],
	[/^border(-.+)?-radius$/, ["radius"]],
	[
		/^(margin|padding|gap|row-gap|column-gap|inset|top|right|bottom|left)(-.+)?$/,
		["space", "size"],
	],
	[/^(min-|max-)?(width|height)$/, ["size", "space"]],
	[/^(transition|animation)(-.+)?-duration$|^(transition|animation)-delay$/, ["duration"]],
];

/** `(1px) -> var(--border-1)` for the declarations whose raw value is one token's value exactly and unambiguously. */
function tokenOfLiteral(prop: string, value: string, foundation: Foundation): string | undefined {
	const groups = PROPERTY_GROUPS.find(([re]) => re.test(prop))?.[1];
	if (!groups) return undefined;
	const hits = foundation.tokens.filter(
		(t) => groups.includes(t.path[0] ?? "") && t.value === value,
	);
	const names = [...new Set(hits.map((t) => t.name))];
	return names.length === 1 ? names[0] : undefined;
}

interface Context {
	foundation: Foundation;
	names: Map<string, string>;
	initial: Map<string, string>;
}

/** A value with the build's variables resolved; null when a `--tw-*` variable has no value anywhere. */
function resolveValue(
	value: string,
	scope: ReadonlyMap<string, string>,
	ctx: Context,
	depth = 0,
): string | null {
	if (depth > 8 || !value.includes("var(")) return value;
	const parsed = valueParser(value);
	let failed = false;
	parsed.walk((node) => {
		if (node.type !== "function" || node.value !== "var") return undefined;
		const name = node.nodes[0]?.value ?? "";
		const comma = node.nodes.findIndex((n) => n.type === "div" && n.value === ",");
		const fallback =
			comma === -1 ? undefined : valueParser.stringify(node.nodes.slice(comma + 1)).trim();
		let replacement: string | null;
		if (name.startsWith("--tw-")) {
			const own = scope.get(name) ?? ctx.initial.get(name);
			if (own !== undefined) replacement = resolveValue(own, scope, ctx, depth + 1);
			else if (fallback !== undefined) replacement = resolveValue(fallback, scope, ctx, depth + 1);
			else replacement = null;
		} else if (name === "--spacing-0") {
			// The generated theme's zero (`p-0`, `min-w-0`): not a step of a scale, and not a token.
			replacement = "0";
		} else if (ctx.names.has(name)) {
			replacement = `var(${ctx.names.get(name)})`;
		} else {
			// Not the foundation's and not the build's own: left as written, the value check names it.
			return false;
		}
		if (replacement === null) {
			failed = true;
			return false;
		}
		const word = node as unknown as { type: string; value: string };
		word.type = "word";
		word.value = replacement;
		return false;
	});
	return failed ? null : parsed.toString();
}

/**
 * The rules of `nodes` whose selectors `keep` accepts, inside the wrappers they sit
 * in — except a `@layer`, which is dropped and its rules kept in place, in the
 * order the build wrote them: the sheet is unlayered, because a mockup's own
 * page styles are, and an unlayered rule beats every layered one whatever its
 * specificity (ADR decision 10, amended 2026-10-12). Among themselves the
 * rules keep the source order, which is what the layers' order gave them.
 */
function keepRules(nodes: readonly ChildNode[], keep: (selector: string) => boolean): ChildNode[] {
	const out: ChildNode[] = [];
	for (const node of nodes) {
		if (node.type === "rule") {
			const kept = node.selectors.filter(keep);
			if (kept.length === 0) continue;
			const copy = node.clone();
			copy.selectors = kept;
			out.push(copy);
		} else if (node.type === "atrule" && node.name === "layer" && node.nodes) {
			out.push(...keepRules(node.nodes, keep));
		} else if (node.type === "atrule" && WRAPPERS.has(node.name) && node.nodes) {
			const inner = keepRules(node.nodes, keep);
			if (inner.length === 0) continue;
			const copy = node.clone({ nodes: [] });
			copy.append(inner);
			out.push(copy);
		}
	}
	return out;
}

/**
 * A selector the component writes: every class it names is one of `classes`;
 * or, naming no class, a rule the app writes on the component's own marker
 * (`[data-component="decision-card"] p`), part of how it draws.
 */
const utilityOf =
	(classes: ReadonlySet<string>, marks: ReadonlySet<string>) =>
	(selector: string): boolean => {
		const used = selectorClasses(selector);
		if (used.length > 0) return used.every((c) => classes.has(c));
		const anchors = selectorMarks(selector);
		return anchors.length > 0 && anchors.every((m) => marks.has(m));
	};

/** Resolve every declaration under `container`; `--tw-*` declarations are the build's own and are dropped. */
function resolveIn(container: Container, parent: ReadonlyMap<string, string>, ctx: Context): void {
	const scope = new Map(parent);
	container.each((child) => {
		if (child.type === "decl" && child.prop.startsWith("--tw-")) scope.set(child.prop, child.value);
	});
	container.each((child) => {
		if (child.type === "decl") {
			if (child.prop.startsWith("--tw-")) return;
			const value = resolveValue(child.value, scope, ctx);
			if (value === null || value.trim() === "") {
				child.remove();
				return;
			}
			child.value = wholeTransition(child.prop, plain(value));
			const token = tokenOfLiteral(child.prop, child.value.trim(), ctx.foundation);
			if (token) child.value = `var(${token})`;
		} else if ("nodes" in child && child.nodes) {
			resolveIn(child as Container, scope, ctx);
		}
	});
	container.each((child) => {
		if (child.type === "decl" && child.prop.startsWith("--tw-")) child.remove();
	});
	// A rule or wrapper emptied by the resolution is no longer a rule.
	container.each((child) => {
		if (
			(child.type === "rule" || child.type === "atrule") &&
			child.nodes &&
			child.nodes.length === 0
		) {
			child.remove();
		}
	});
}

/**
 * What the build writes that the value check reads differently from CSS:
 * a zero length with a unit is `0`, and `currentcolor` is `currentColor`.
 */
function plain(value: string): string {
	const parsed = valueParser(value);
	parsed.walk((node) => {
		if (node.type !== "word") return;
		if (/^-?(?:0+\.?0*|\.0+)(?:px|rem|em)$/.test(node.value)) node.value = "0";
		else if (/^currentcolor$/i.test(node.value)) node.value = "currentColor";
	});
	return parsed.toString();
}

/**
 * `transition-property: color, background-color, …` (Tailwind's `transition-colors`)
 * is a list of property names, which the value check holds to one keyword; the
 * list becomes `all`, with the duration and easing the utility already names.
 */
const wholeTransition = (prop: string, value: string): string =>
	prop === "transition-property" && value.includes(",") ? "all" : value;

/** The `animation` names the declarations under `nodes` use. */
function animationNames(nodes: readonly ChildNode[]): Set<string> {
	const names = new Set<string>();
	const visit = (list: readonly ChildNode[]) => {
		for (const n of list) {
			if (n.type === "decl" && /^animation(-name)?$/.test(n.prop)) {
				valueParser(n.value).walk((v) => {
					if (v.type === "word") names.add(v.value);
				});
			} else if ("nodes" in n && n.nodes) visit(n.nodes);
		}
	};
	visit(nodes);
	return names;
}

/**
 * The app's compiled rules for `classes` — and the rules the app writes on the
 * component markers in `marks`, which name no class — in the order the build wrote them,
 * with the build's variables resolved to the foundation's tokens. Empty (just
 * the header) when none of the classes has a rule.
 */
export function componentStylesheet(
	appCss: string,
	classes: ReadonlySet<string>,
	foundation: Foundation,
	marks: ReadonlySet<string> = new Set(),
): string {
	const root = postcss.parse(appCss);
	const ctx = contextOf(root, foundation);

	const out = postcss.root();
	const kept = keepRules(root.nodes, utilityOf(classes, marks));
	out.append(kept);

	const used = animationNames(kept);
	if (used.size > 0) {
		const seen = new Set<string>();
		root.walkAtRules(/^(-\w+-)?keyframes$/, (at) => {
			if (used.has(at.params.trim()) && !seen.has(at.params.trim())) {
				seen.add(at.params.trim());
				out.append(at.clone());
			}
		});
	}
	return sheetOf(out, ctx);
}

/**
 * The app's base stylesheet, `components/_base.css`: its compiled `body` rules —
 * the font, ink and ground every component inherits in the app — resolved to the
 * foundation's tokens as a component's sheet is. A story's frame loads it under
 * the component's sheet, so a snapshot is drawn in the app's type rather than the
 * browser's default. Not part of any approval: a component's look is its own sheet.
 */
export function baseStylesheet(appCss: string, foundation: Foundation): string {
	const root = postcss.parse(appCss);
	const out = postcss.root();
	out.append(keepRules(root.nodes, (selector) => selector.trim() === "body"));
	return sheetOf(out, contextOf(root, foundation));
}

/** A selector naming no class and no component marker: an element, universal or page rule of the app. */
const isElementSelector = (selector: string): boolean =>
	selectorClasses(selector).length === 0 && selectorMarks(selector).length === 0;

/** Where a story's frame holds a component: the marker's own element and everything inside it. */
const COMPONENT_SCOPE = ":where([data-component], [data-component] *)";

/** A selector that names the page itself; the page is not a component, so `_base.css` and the page hold these. */
const PAGE_SELECTOR = /(^|[\s>+~(])(html|body|:root|:host)(?![\w-])/;

/** Index of the first `::` outside brackets and parentheses, or -1: the pseudo-element a scope must come before. */
function pseudoElementAt(selector: string): number {
	let depth = 0;
	for (let i = 0; i < selector.length; i++) {
		const c = selector[i];
		if (c === "(" || c === "[") depth++;
		else if (c === ")" || c === "]") depth--;
		else if (depth === 0 && c === ":" && selector[i + 1] === ":") return i;
	}
	return -1;
}

/** `selector` with `guard` appended, before its pseudo-element when it has one: after it the selector is invalid and a browser drops the whole rule. */
function guarded(selector: string, guard: string): string {
	const s = selector.trim();
	const at = pseudoElementAt(s);
	return at === -1 ? `${s}${guard}` : `${s.slice(0, at)}${guard}${s.slice(at)}`;
}

/** `a:hover` -> `a:hover:where(<scope>)`, `::before` -> `:where(<scope>)::before`: the scope adds no specificity. */
const scoped = (selector: string): string => guarded(selector, COMPONENT_SCOPE);

/** What a mockup's own rule must not reach: any element of a component. `:not(:where())` adds no specificity. */
const OUTSIDE_COMPONENTS = `:not(${COMPONENT_SCOPE})`;

/**
 * A mockup's own style rules, cut to its page. A mockup's `.grid { display: grid }`
 * would otherwise reach a placed component that also uses a `grid` class and draw
 * it differently from its story, so each selector gains the inverse of
 * `componentReset`'s scope. A selector that names a component's marker
 * (`[data-component="card"] .grid`) is the mockup placing that component and
 * is left as written; rules inside `@keyframes` have no selector to scope.
 *
 * promise: mockups-render-in-the-cockpit
 */
export function pageOnly(css: string): string {
	let root: postcss.Root;
	try {
		root = postcss.parse(css);
	} catch {
		return css;
	}
	root.walkRules((rule) => {
		const parent = rule.parent;
		if (parent?.type === "atrule" && /keyframes$/i.test((parent as postcss.AtRule).name)) return;
		rule.selectors = rule.selectors.map((selector) =>
			selectorMarks(selector).length > 0 ? selector : guarded(selector, OUTSIDE_COMPONENTS),
		);
	});
	return root.toString();
}

const VARIANT_AT_RULES = /^(media|supports|container)$/i;

/**
 * A component's stylesheet cut into its plain rules and its variant rules, a
 * rule under `@media`, `@supports` or `@container`, or one that nests such a
 * block (`.max-\[759px\]:hidden { @media … }`). The app's build writes every
 * variant after every plain utility, so a variant beats a plain rule of the
 * same specificity; a mockup loads one sheet per component, and `.flex` in a
 * later sheet would beat an earlier sheet's `max-[759px]:hidden`. The cockpit
 * therefore puts all the variants after all the plain rules, each in the order
 * its sheet wrote it. Only where a rule sits changes; no hash reads this.
 *
 * promise: mockups-render-in-the-cockpit
 */
export function splitVariants(css: string): { plain: string; variants: string } {
	let root: postcss.Root;
	try {
		root = postcss.parse(css);
	} catch {
		return { plain: css, variants: "" };
	}
	const variants = postcss.root();
	for (const node of [...(root.nodes ?? [])]) {
		const isVariant =
			(node.type === "atrule" && VARIANT_AT_RULES.test(node.name)) ||
			(node.type === "rule" &&
				node.some((n) => n.type === "atrule" && VARIANT_AT_RULES.test(n.name)));
		if (isVariant) variants.append(node);
	}
	return { plain: root.toString(), variants: variants.toString() };
}

/**
 * The app's element resets as a sheet that reaches only components,
 * `components/_reset.css`. A story renders in the served Storybook under the
 * app's element rules (`a { color: inherit }`, `textarea { font: inherit }`),
 * and no component's slice holds them, so a component drawn in a mockup came
 * out in the browser's defaults. These are those rules (`elementRulesOf`'s: no
 * class, no marker), each selector written under `:where([data-component],
 * [data-component] *)` so they add no specificity and touch nothing outside a
 * component. Rules naming the page (`html`, `body`, `:root`, `:host`) are left
 * out: `_base.css` holds `body`, and a mockup's page is its own.
 *
 * promise: mockups-render-in-the-cockpit
 */
export function componentReset(appCss: string, foundation: Foundation): string {
	const root = postcss.parse(appCss);
	const out = postcss.root();
	out.append(
		keepRules(
			root.nodes,
			(selector) => isElementSelector(selector) && !PAGE_SELECTOR.test(selector),
		),
	);
	out.walkRules((rule) => {
		rule.selectors = rule.selectors.map(scoped);
	});
	return sheetOf(out, contextOf(root, foundation));
}

/**
 * The rules of the app's compiled CSS that no class and no component marker
 * names — element, universal, `html`, `:root` and `body` rules, wherever they
 * sit — printed as the build wrote them. Every story draws under them in the
 * served Storybook, and no component's slice holds them, so the render step
 * records their hash in the catalog (`baseRulesHash`) and a story's reuse
 * depends on it: an `a` or `*` rule changed in the app's stylesheet reopens
 * every story (looks-check-speed A30). Unresolved on purpose — any byte the
 * build changes moves the hash.
 *
 * promise: tokens-are-held-exactly
 */
export function elementRulesOf(appCss: string): string {
	const out = postcss.root();
	out.append(keepRules(postcss.parse(appCss).nodes, isElementSelector));
	out.walk((n) => {
		n.cleanRaws();
	});
	return out.toString().trim();
}

/** The build's `@property` initial values, and the foundation's names for its variables. */
function contextOf(root: postcss.Root, foundation: Foundation): Context {
	const initial = new Map<string, string>();
	root.walkAtRules("property", (at) => {
		at.walkDecls("initial-value", (d) => {
			initial.set(at.params.trim(), d.value);
		});
	});
	return { foundation, names: themeNames(foundation), initial };
}

/** `out` resolved and printed under the header; just the header when no rule is left. */
function sheetOf(out: postcss.Root, ctx: Context): string {
	resolveIn(out, new Map(), ctx);
	out.walk((n) => {
		n.cleanRaws();
	});
	const body = out.toString().trim();
	return body === "" ? STYLESHEET_HEADER : `${STYLESHEET_HEADER}${body}\n`;
}
